import type { Analysis, Operation } from "@tracekit/core";
import { stringify } from "yaml";

const STATUS_TEXT: Record<string, string> = {
  "200": "OK",
  "201": "Created",
  "202": "Accepted",
  "204": "No content",
  "301": "Moved permanently",
  "302": "Found",
  "304": "Not modified",
  "400": "Bad request",
  "401": "Unauthorized",
  "403": "Forbidden",
  "404": "Not found",
  "409": "Conflict",
  "422": "Unprocessable entity",
  "429": "Too many requests",
  "500": "Internal server error",
};

const SECURITY_NAME = { bearer: "bearerAuth", apiKey: "apiKeyAuth", cookie: "cookieAuth" } as const;

function securityScheme(analysis: Analysis): Record<string, unknown> | undefined {
  const scheme = analysis.auth.scheme;
  switch (scheme.type) {
    case "bearer":
      return { [SECURITY_NAME.bearer]: { type: "http", scheme: "bearer" } };
    case "apiKey":
      return { [SECURITY_NAME.apiKey]: { type: "apiKey", in: scheme.in, name: scheme.name } };
    case "cookie":
      return { [SECURITY_NAME.cookie]: { type: "apiKey", in: "cookie", name: scheme.names[0] ?? "session" } };
    case "none":
      return undefined;
  }
}

function operationObject(op: Operation, analysis: Analysis): Record<string, unknown> {
  const parameters = [
    ...op.pathParams.map((p) => ({ name: p.name, in: "path", required: true, schema: p.schema })),
    ...op.queryParams.map((p) => ({ name: p.name, in: "query", required: p.required, schema: p.schema })),
  ];
  const responses = Object.fromEntries(
    Object.entries(op.responses).map(([status, res]) => [
      status,
      {
        description: STATUS_TEXT[status] ?? `HTTP ${status}`,
        ...(res.schema ? { content: { [res.contentType ?? "application/json"]: { schema: res.schema } } } : {}),
      },
    ]),
  );
  const scheme = analysis.auth.scheme;
  return {
    operationId: op.id,
    summary: op.summary,
    description: op.description,
    tags: [op.tag],
    ...(parameters.length ? { parameters } : {}),
    ...(op.requestBody
      ? { requestBody: { required: true, content: { [op.requestBody.contentType]: { schema: op.requestBody.schema } } } }
      : {}),
    responses,
    ...(scheme.type !== "none" ? { security: op.authenticated ? [{ [SECURITY_NAME[scheme.type]]: [] }] : [] } : {}),
    "x-tracekit-calls": op.calls,
  };
}

export function buildOpenApi(analysis: Analysis, apiDescription?: string): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const op of analysis.operations) {
    (paths[op.path] ??= {})[op.method.toLowerCase()] = operationObject(op, analysis);
  }
  const schemes = securityScheme(analysis);
  const note =
    `Generated by tracekit from ${analysis.stats.apiCalls} recorded calls. ` +
    "Schemas are inferred from samples: treat them as a starting point and verify before relying on them.";
  return {
    openapi: "3.1.0",
    info: {
      title: analysis.title,
      version: "0.1.0",
      description: apiDescription ? `${apiDescription}\n\n${note}` : note,
    },
    servers: [{ url: analysis.baseUrl }],
    tags: [...new Set(analysis.operations.map((op) => op.tag))].map((name) => ({ name })),
    paths,
    ...(schemes ? { components: { securitySchemes: schemes } } : {}),
    "x-tracekit": {
      auth: analysis.auth,
      callGraph: analysis.graph,
    },
  };
}

export function renderOpenApi(analysis: Analysis, apiDescription?: string): string {
  return stringify(buildOpenApi(analysis, apiDescription), { lineWidth: 0, aliasDuplicateObjects: false });
}
