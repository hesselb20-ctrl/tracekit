import type { Analysis, JsonSchema, Operation } from "@tracekit/core";
import { credentialIssuer, pascal, successResponse } from "./util.js";

const HEADER = "// Generated by tracekit. Re-run `tracekit build` instead of editing by hand.\n";
const IDENT = /^[A-Za-z_$][\w$]*$/;

/** JSON Schema (the subset tracekit infers) to a TypeScript type expression. */
export function schemaToTs(schema: JsonSchema | undefined, indent = ""): string {
  if (!schema || schema.type === undefined) return "unknown";
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const parts = types.map((type) => {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const item = schemaToTs(schema.items, indent);
        return /[|\s]/.test(item) && !item.startsWith("{") ? `(${item})[]` : `${item}[]`;
      }
      case "object": {
        const props = Object.entries(schema.properties ?? {});
        if (props.length === 0) return "Record<string, unknown>";
        const inner = indent + "  ";
        const lines = props.map(([key, value]) => {
          const name = IDENT.test(key) ? key : JSON.stringify(key);
          const optional = schema.required?.includes(key) ? "" : "?";
          return `${inner}${name}${optional}: ${schemaToTs(value, inner)};`;
        });
        return `{\n${lines.join("\n")}\n${indent}}`;
      }
      default:
        return "unknown";
    }
  });
  return [...new Set(parts)].join(" | ");
}

interface Shape {
  op: Operation;
  type: string;
  bodyType?: string;
  queryType?: string;
  responseType: string;
}

function shapes(analysis: Analysis): Shape[] {
  return analysis.operations.map((op) => {
    const type = pascal(op.id);
    const ok = successResponse(op);
    return {
      op,
      type,
      bodyType: op.requestBody ? `${type}Body` : undefined,
      queryType: op.queryParams.length ? `${type}Query` : undefined,
      responseType: ok?.hasBody ? `${type}Response` : "void",
    };
  });
}

export function renderTypes(analysis: Analysis): string {
  const out: string[] = [HEADER];
  for (const s of shapes(analysis)) {
    const { op } = s;
    out.push(`// ${op.method} ${op.path}`);
    if (s.bodyType) out.push(`export type ${s.bodyType} = ${schemaToTs(op.requestBody!.schema)};\n`);
    if (s.queryType) {
      const lines = op.queryParams.map((p) => {
        const name = IDENT.test(p.name) ? p.name : JSON.stringify(p.name);
        return `  ${name}${p.required ? "" : "?"}: ${schemaToTs(p.schema)};`;
      });
      out.push(`export type ${s.queryType} = {\n${lines.join("\n")}\n};\n`);
    }
    if (s.responseType !== "void") {
      const ok = successResponse(op)!;
      out.push(`export type ${s.responseType} = ${schemaToTs(op.responses[ok.status]!.schema)};\n`);
    }
  }
  return out.join("\n");
}

function docComment(op: Operation, extra?: string): string {
  const lines = [op.summary, "", ...op.description.split("\n"), ...(extra ? ["", extra] : [])];
  return ["  /**", ...lines.map((l) => (l ? `   * ${l}` : "   *")), "   */"].join("\n");
}

export function renderClient(analysis: Analysis, name: string): string {
  const className = `${pascal(name)}Client`;
  const scheme = analysis.auth.scheme;
  const issuer = credentialIssuer(analysis);

  const optionDocs: string[] = [];
  let applyAuth = "";
  if (scheme.type === "bearer") {
    optionDocs.push("  /** Bearer token sent as the Authorization header. */\n  token?: string;");
    applyAuth = `    if (auth && this.credential) headers["authorization"] = \`Bearer \${this.credential}\`;`;
  } else if (scheme.type === "apiKey" && scheme.in === "header") {
    optionDocs.push(`  /** API key sent as the ${scheme.name} header. */\n  apiKey?: string;`);
    applyAuth = `    if (auth && this.credential) headers[${JSON.stringify(scheme.name)}] = this.credential;`;
  } else if (scheme.type === "apiKey") {
    optionDocs.push(`  /** API key sent as the ${scheme.name} query parameter. */\n  apiKey?: string;`);
    applyAuth = `    if (auth && this.credential) url.searchParams.set(${JSON.stringify(scheme.name)}, this.credential);`;
  } else if (scheme.type === "cookie") {
    optionDocs.push(
      `  /** Cookie header value, e.g. "${scheme.names[0] ?? "session"}=...". Browsers manage cookies themselves; this is for Node. */\n  cookie?: string;`,
    );
    applyAuth = `    if (auth && this.credential) headers["cookie"] = this.credential;`;
  }
  const credentialOption =
    scheme.type === "bearer" ? "token" : scheme.type === "apiKey" ? "apiKey" : scheme.type === "cookie" ? "cookie" : "";

  const methods = shapes(analysis).map((s) => {
    const { op } = s;
    const args: string[] = op.pathParams.map((p) => `${p.name}: ${schemaToTs(p.schema)}`);
    if (s.bodyType) args.push(`body: T.${s.bodyType}`);
    if (s.queryType) {
      const anyRequired = op.queryParams.some((p) => p.required);
      args.push(anyRequired ? `query: T.${s.queryType}` : `query: T.${s.queryType} = {}`);
    }
    const path = op.path.replace(/\{(\w+)\}/g, (_m, p: string) => `\${encodeURIComponent(String(${p}))}`);
    const init = [
      s.queryType ? "query" : "",
      s.bodyType ? "body" : "",
      `auth: ${op.authenticated}`,
    ].filter(Boolean);
    const ret = s.responseType === "void" ? "void" : `T.${s.responseType}`;
    const call = `this.request<${ret}>("${op.method}", \`${path}\`, { ${init.join(", ")} })`;
    const captures = issuer?.op === op && issuer.field && credentialOption !== "";
    const body = captures
      ? [
          `    const result = await ${call};`,
          `    const issued = (result as any)?.${issuer!.field!.split(".").join("?.")};`,
          `    if (typeof issued === "string") this.credential = issued;`,
          `    return result;`,
        ].join("\n")
      : `    return ${call};`;
    const extra = captures ? "The credential in the response is stored on the client and used for later calls." : undefined;
    return `${docComment(op, extra)}\n  async ${op.id}(${args.join(", ")}): Promise<${ret}> {\n${body}\n  }`;
  });

  return `${HEADER}
import type * as T from "./types.js";

export interface ClientOptions {
  /** Defaults to ${analysis.baseUrl} */
  baseUrl?: string;
${optionDocs.join("\n")}${optionDocs.length ? "\n" : ""}  /** Extra headers for every request. */
  headers?: Record<string, string>;
  /** Custom fetch implementation. Defaults to the global fetch. */
  fetch?: typeof fetch;
}

export class ApiError extends Error {
  constructor(
    readonly status: number,
    readonly body: unknown,
    message: string,
  ) {
    super(message);
    this.name = "ApiError";
  }
}

export class ${className} {
  private readonly baseUrl: string;
  private readonly fetchImpl: typeof fetch;
  private readonly extraHeaders: Record<string, string>;
  private credential: string | undefined;

  constructor(options: ClientOptions = {}) {
    this.baseUrl = (options.baseUrl ?? ${JSON.stringify(analysis.baseUrl)}).replace(/\\/+$/, "");
    this.fetchImpl = options.fetch ?? globalThis.fetch.bind(globalThis);
    this.extraHeaders = options.headers ?? {};
    this.credential = ${credentialOption ? `options.${credentialOption}` : "undefined"};
  }

  /** Replace the credential used for authenticated calls. */
  setCredential(value: string | undefined): void {
    this.credential = value;
  }

  private async request<R>(
    method: string,
    path: string,
    init: { query?: object; body?: unknown; auth: boolean },
  ): Promise<R> {
    const { auth } = init;
    const url = new URL(this.baseUrl + path);
    for (const [key, value] of Object.entries(init.query ?? {})) {
      if (value !== undefined && value !== null) url.searchParams.set(key, String(value));
    }
    const headers: Record<string, string> = { accept: "application/json", ...this.extraHeaders };
    if (init.body !== undefined) headers["content-type"] = "application/json";
${applyAuth || "    void auth;"}

    const response = await this.fetchImpl(url, {
      method,
      headers,
      body: init.body === undefined ? undefined : JSON.stringify(init.body),
    });
    const text = await response.text();
    let data: unknown = text;
    try {
      data = text === "" ? undefined : JSON.parse(text);
    } catch {
      // not JSON: keep the raw text
    }
    if (!response.ok) throw new ApiError(response.status, data, \`\${method} \${path} failed with \${response.status}\`);
    return data as R;
  }

${methods.join("\n\n")}
}

export function createClient(options: ClientOptions = {}): ${className} {
  return new ${className}(options);
}
`;
}

export function renderSdkIndex(): string {
  return `${HEADER}\nexport * from "./client.js";\nexport type * from "./types.js";\n`;
}
